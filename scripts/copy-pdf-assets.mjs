import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const pdfjsDistPath = path.dirname(require.resolve('pdfjs-dist/package.json'))
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pdfjsVersion = JSON.parse(
  fs.readFileSync(path.join(pdfjsDistPath, 'package.json'), 'utf8'),
).version
const publicPdfjsPath = path.join(projectRoot, 'public', 'pdfjs')
const versionedPdfjsPath = path.join(publicPdfjsPath, pdfjsVersion)

fs.mkdirSync(publicPdfjsPath, { recursive: true })
// Every directory here is generated by this script. Remove old versions so a
// deployment cannot accidentally serve CMaps that do not match its PDF.js.
for (const entry of fs.readdirSync(publicPdfjsPath, { withFileTypes: true })) {
  if (entry.isDirectory() && entry.name !== pdfjsVersion) {
    fs.rmSync(path.join(publicPdfjsPath, entry.name), { recursive: true, force: true })
  }
}

// Keep CMaps in a versioned public path so PDF.js can fetch them from the same
// origin and immutable caching cannot serve a map from another PDF.js version.
for (const directory of ['cmaps', 'standard_fonts', 'wasm', 'iccs']) {
  fs.cpSync(
    path.join(pdfjsDistPath, directory),
    path.join(versionedPdfjsPath, directory),
    { recursive: true },
  )
}

// The offline saver warms the PDF resources explicitly instead of relying on
// which pages happened to render before Save was pressed.
const runtimeExtensions = new Set(['.bcmap', '.pfb', '.ttf', '.wasm', '.js', '.icc'])
const pdfAssets = ['cmaps', 'standard_fonts', 'wasm', 'iccs']
  .flatMap((directory) => fs.readdirSync(path.join(versionedPdfjsPath, directory))
    .filter((name) => runtimeExtensions.has(path.extname(name)))
    .map((name) => `/pdfjs/${pdfjsVersion}/${directory}/${name}`))
  .sort()
fs.writeFileSync(
  path.join(publicPdfjsPath, 'offline-manifest.json'),
  `${JSON.stringify({ pdfjsVersion, assets: pdfAssets }, null, 2)}\n`,
)
