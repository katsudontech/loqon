import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const pdfjsDistPath = path.dirname(require.resolve('pdfjs-dist/package.json'))
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pdfjsVersion = JSON.parse(
  fs.readFileSync(path.join(pdfjsDistPath, 'package.json'), 'utf8'),
).version
const publicPdfjsPath = path.join(projectRoot, 'public', 'pdfjs')
const versionedCMapsPath = path.join(publicPdfjsPath, pdfjsVersion, 'cmaps')

fs.mkdirSync(publicPdfjsPath, { recursive: true })
// Every directory here is generated by this script. Remove old versions so a
// deployment cannot accidentally serve CMaps that do not match its PDF.js.
for (const entry of fs.readdirSync(publicPdfjsPath, { withFileTypes: true })) {
  if (entry.isDirectory() && entry.name !== pdfjsVersion) {
    fs.rmSync(path.join(publicPdfjsPath, entry.name), { recursive: true, force: true })
  }
}

// Keep CMaps in a versioned public path so PDF.js can fetch them from the same
// origin and immutable caching cannot serve a map from another PDF.js version.
fs.cpSync(
  path.join(pdfjsDistPath, 'cmaps'),
  versionedCMapsPath,
  { recursive: true },
)
